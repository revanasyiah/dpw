<?php
$x = 5;
$y = 10;

// Aritmatika
echo "Penjumlahan: " . ($x + $y) . "<br>";
echo "Pengurangan: " . ($x - $y) . "<br>";
echo "Perkalian: " . ($x * $y) . "<br>";
echo "Pembagian: " . ($x / $y) . "<br>";
echo "Modulus: " . ($x % $y) . "<br>";

// Assignment
$x += 2;
$y *= 2;

echo "x setelah +=2: $x <br>";
echo "y setelah *=2: $y <br>";

// Increment
echo "x++: " . $x++ . "<br>";
echo "++x: " . ++$x . "<br>";